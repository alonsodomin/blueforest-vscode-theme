-- The colours of the rainbow delimiters.
--
-- The rainbow-delimiters plugin paints the delimiters of a buffer with the
-- highlight groups it is told to use, and it reads their colours from the
-- colourscheme. A group that the colourscheme does not define has no colour
-- to give, so the rainbow does not show. These are the seven groups the
-- plugin uses by default, one for each level of nesting.
local rainbow = {
  RainbowDelimiterRed = { fg = palette.diff_del },
  RainbowDelimiterOrange = { fg = palette.status_debug },
  RainbowDelimiterYellow = { fg = palette.operator },
  RainbowDelimiterGreen = { fg = palette.string },
  RainbowDelimiterCyan = { fg = palette.diff_add },
  RainbowDelimiterBlue = { fg = palette.accent },
  RainbowDelimiterViolet = { fg = palette.function_blue },
}

function M.setup()
  vim.g.colors_name = "blueforest"
  vim.o.background = "dark"

  for group, hl in pairs(groups) do
    vim.api.nvim_set_hl(0, group, hl)
  end
  for group, hl in pairs(treesitter) do
    vim.api.nvim_set_hl(0, group, hl)
  end
  for group, hl in pairs(diagnostics) do
    vim.api.nvim_set_hl(0, group, hl)
  end
  for group, hl in pairs(git) do
    vim.api.nvim_set_hl(0, group, hl)
  end
  for group, hl in pairs(plugins) do
    vim.api.nvim_set_hl(0, group, hl)
  end
  for group, hl in pairs(rainbow) do
    vim.api.nvim_set_hl(0, group, hl)
  end
end

M.setup()
return M
